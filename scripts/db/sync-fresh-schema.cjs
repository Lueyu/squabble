#!/usr/bin/env node
// Fresh installs include the complete current schema. Existing databases use additive migrations.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname);
const file = path.join(root, '01_schema.sql');
const marker = '-- Consolidated additive schema for fresh installations.';
let base = fs.readFileSync(file, 'utf8').split(marker)[0].trimEnd();
const migrations = fs.readdirSync(root).filter(name => /^\d{2}_.*\.sql$/.test(name) && Number(name.slice(0, 2)) >= 3).sort();
base += '\n\n' + marker + '\n-- Generated by scripts/db/sync-fresh-schema.cjs. Upgrade files remain authoritative.\n';
for (const name of migrations) base += '\n-- ' + name + '\n' + fs.readFileSync(path.join(root, name), 'utf8').trim() + '\n';
fs.writeFileSync(file, base);
console.log('Fresh schema synchronized with ' + migrations.length + ' migrations.');
