    assert.equal(seed.seed.initialEquityUsd, null);
    assert.equal((await new SimulationExperimentsService(db, {} as never, {} as never).get(owner, one.accountId)).sourceChanged, false, 'virtual cash must not falsely claim that real assets changed');
    const nextPreview = await service.preview(owner, { origin: 'holdings', requestKey: 'copy-preview-002' });
    const next = await service.restart(owner, { previewId: nextPreview.id, expectedAccountId: one.accountId, requestKey: 'copy-start-0002' });
